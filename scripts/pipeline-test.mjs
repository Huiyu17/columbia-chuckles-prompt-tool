import ts from 'typescript';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const code = ts.transpileModule(await readFile(new URL('../lib/pipeline.ts', import.meta.url),'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { executeChain } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const humorCode = ts.transpileModule(await readFile(new URL('../lib/humor.ts', import.meta.url),'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { originalScene, humorStyles } = await import(`data:text/javascript;base64,${Buffer.from(humorCode).toString('base64')}`);
const mediaCode = ts.transpileModule(await readFile(new URL('../lib/media-query.ts', import.meta.url),'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { mediaHref, mediaSource, mediaStatus } = await import(`data:text/javascript;base64,${Buffer.from(mediaCode).toString('base64')}`);
assert.equal(mediaHref('chain-id','caption-app',2),'/?view=media&chain=chain-id&source=caption-app&page=2');
assert.equal(mediaHref('chain-id','prompt-tool'),'/?view=media&chain=chain-id&source=prompt-tool');
assert.equal(mediaHref(null,null),'/?view=media');
assert.equal(mediaSource('caption-app'),'caption-app');assert.equal(mediaSource('prompt-tool'),'prompt-tool');assert.equal(mediaSource('invalid'),null);
for(const status of ['completed','failed','running','pending']) assert.equal(mediaStatus(status),status);
assert.equal(mediaStatus('invalid'),null);
assert.equal(mediaHref('chain-id','caption-app',2,'failed'),'/?view=media&chain=chain-id&source=caption-app&status=failed&page=2');
assert.equal(mediaHref('chain-id','prompt-tool',1,'completed'),'/?view=media&chain=chain-id&source=prompt-tool&status=completed');
const sceneText = 'Five alarms.\nStill asleep.\nSelected humor style: my own words';
for (const style of humorStyles) assert.equal(originalScene(`${sceneText}\n\nSelected humor style: ${style.name}. ${style.instruction}`), sceneText);
assert.equal(originalScene(sceneText),sceneText);
assert.equal(originalScene('An ordinary public scene.'),'An ordinary public scene.');
const plan = { scene:'Finals at Butler', description:'A student asleep over a textbook', steps:[{prompt:'Describe the photo', model:'test-one'}, {prompt:'Find the joke', model:'test-two'}, {prompt:'Write five captions', model:'test-three'}] };
const calls=[], records=[];
const output = await executeChain(plan,async input => { calls.push(input); return {text:`real output ${calls.length}`,inputTokens:10,outputTokens:4}; },async step => records.push(step));
assert.equal(output,'real output 3'); assert.equal(calls.length,3);
assert.ok(calls[0].prompt.includes('Finals at Butler')); assert.ok(calls[0].includePhoto);
assert.ok(calls[1].prompt.includes('real output 1')); assert.equal(calls[1].includePhoto,false);
assert.ok(calls[2].prompt.includes('real output 2')); assert.ok(!calls[2].prompt.includes('real output 1'));
assert.deepEqual(records.map(step=>step.model),['test-one','test-two','test-three']);
assert.deepEqual(records.map(step=>step.order),[0,1,2]);
const styledCalls = [], styledRecords = [];
await executeChain({...plan, humorStyle:'Dry & deadpan. Use understated humor.'}, async input => {
  styledCalls.push(input); return {text:'Styled output'};
}, async step => styledRecords.push(step));
assert.equal(styledCalls.length,3);
assert.ok(styledCalls.every(call => call.prompt.includes('Selected humor style: Dry & deadpan. Use understated humor.')));
assert.ok(styledRecords.every(step => step.prompt.includes('Dry & deadpan')));
let count=0;
await assert.rejects(()=>executeChain(plan,async()=>{ if (++count===2) throw Error('Provider failure'); return {text:'kept intermediate'}; },async()=>{}));
assert.equal(count,2);
await assert.rejects(()=>executeChain(plan,async()=>({text:'  '}),async()=>{}),/empty/);
await assert.rejects(()=>executeChain(plan,async()=>({text:'a'.repeat(20001)}),async()=>{}),/oversized/);
await assert.rejects(()=>executeChain({...plan,steps:[]},async()=>({text:'x'}),async()=>{}));
count=0;
await assert.rejects(()=>executeChain(plan,async()=>{count++;return {text:'x'};},async()=>{throw Error('Persistence failure');}));
assert.equal(count,1);
let tokenRecord;
await executeChain({...plan,steps:plan.steps.slice(0,1)},async()=>({text:'caption'}),async step=>{tokenRecord=step;});
assert.equal(tokenRecord.inputTokens,null); assert.equal(tokenRecord.outputTokens,null);
console.log('Pipeline checks passed: sequential inputs, model selection, first-step image, intermediate persistence, stop on failures, bounds and real usage. No paid model calls.');
